#덧셈(+)
result = 5 + 3  # 결과: 8
print(result)

#뺄셈(-)
result = 5 - 3  # 결과: 2
print(result)

#곱셈(*)
result = 5 * 3  # 결과: 15
print(result)

#나눗셈(/)
result = 5 / 2 # 결과: 2.5
print(result)

#몫(//)
result = 5 // 2  # 결과: 2
print(result)

#나머지(%)
result = 5 // 2  # 결과: 2
print(result)

#거듭제곱(**)
result = 2**3  # 결과: 2
print(result)

#우선순위 예시
# 곱셈이 먼저 처리되고, 그 다음 덧셈이 연산됨
result = 2 + 3 * 4  # 결과: 14
print(result)

# 괄호를 사용해 우선순위 변경
result = (2 + 3) * 4  # 결과: 20
print(result)