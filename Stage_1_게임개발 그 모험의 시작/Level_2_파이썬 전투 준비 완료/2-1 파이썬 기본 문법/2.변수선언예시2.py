# 변수 선언

age = 19              # 정수(int)
height = 165.3        # 실수(float)
is_pretty = True      # 불리언(bool)
empty = None          # null 타입. 비어 있음을 뜻합니다.

# 변수 출력
print(age)			# 출력: 19
print(height)			# 출력: 165.3
print(is_pretty)		# 출력: True
print(empty)			# 출력 : None
#print(undefined)			# 출력 : 에러 출력
