# 문자열 출력
print("Hello, World!")

# 변수 출력
x = 42
print("The value of x is:", x)

# 여러 값을 출력
name = "Alice"
age = 25

#덧셈 연산자로 표시하는 방법
print("이름:" + name + ", 나이:" + str(age) +"세")

#f-string을 이용하는 방법
print(f"{name} is {age} years old.")

#실행 결과
#Hello, World!
#The value of x is: 42
#이름:Alice, 나이:25세
#Alice is 25 years old.
